    import math
    out=[]
    for i,p in enumerate(points):
        a=points[i-1];b=points[(i+1)%len(points)]
        def towards(q):
            d=math.dist(p,q);return (p[0]+(q[0]-p[0])*cut/d,p[1]+(q[1]-p[1])*cut/d)
        u=towards(a);v=towards(b)
        for t in (0,.2,.4,.6,.8,1):out.append((round((1-t)**2*u[0]+2*t*(1-t)*p[0]+t*t*v[0],3),round((1-t)**2*u[1]+2*t*(1-t)*p[1]+t*t*v[1],3)))
    return out

